export function PixelText({ text, px = 3, color = 'var(--gold-hi)', shadow = '#3a2a10', title }: { text: string; px?: number; color?: string; shadow?: string; title?: string }) {
  const chars = text.toUpperCase().split('')
  const rects: Array<[number, number]> = []
  let x = 0
  for (const ch of chars) {
    const g = G[ch] ?? G['?']!
    g.forEach((row, y) => row.split('').forEach((b, dx) => b === '1' && rects.push([x + dx, y])))
    x += (g[0]?.length ?? 3) + 1
  }
  const w = Math.max(1, x - 1)
  return (
    <svg role="img" aria-label={title ?? text} width={(w + 1) * px} height={8 * px} viewBox={`0 0 ${w + 1} 8`} shapeRendering="crispEdges" style={{ display: 'block' }}>
      {rects.map(([rx, ry], i) => (
        <rect key={`s${i}`} x={rx + 1} y={ry + 1} width={1} height={1} fill={shadow} />
      ))}
      {rects.map(([rx, ry], i) => (
        <rect key={`f${i}`} x={rx} y={ry} width={1} height={1} fill={color} />
      ))}
    </svg>
  )
}
